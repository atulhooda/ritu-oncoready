"""Render synthetic case documents as scanned-looking PDFs and write REVIEW_FOR_DOCTOR.md.

Each PDF page is a raster image (no text layer), so the pipeline must OCR it. Pages from
outside facilities get skew, noise, and blur. Deterministic (seeded RNG).

    backend/.venv/bin/python seed/render.py
"""

import json
import random
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

HERE = Path(__file__).resolve().parent
CASES = HERE / "cases"
W, H = 1275, 1650  # US letter at 150 dpi
MARGIN = 110
FONT = ImageFont.load_default(size=27)
FONT_BOLD = ImageFont.load_default(size=34)
FONT_SMALL = ImageFont.load_default(size=20)


def render_page(lines: list[str], facility: str, page_no: int, n_pages: int) -> Image.Image:
    img = Image.new("L", (W, H), 255)
    d = ImageDraw.Draw(img)
    d.text((MARGIN, 70), facility, font=FONT_SMALL, fill=60)
    d.text((MARGIN, 96), "SYNTHETIC TRAINING DOCUMENT - NOT A REAL PATIENT", font=FONT_SMALL, fill=60)
    d.line((MARGIN, 128, W - MARGIN, 128), fill=0, width=2)
    y = 170
    for i, line in enumerate(lines):
        d.text((MARGIN, y), line, font=FONT_BOLD if i == 0 else FONT, fill=0)
        y += 58 if i == 0 else 46
    d.text((W - MARGIN - 130, H - 90), f"Page {page_no} of {n_pages}", font=FONT_SMALL, fill=60)
    return img


def degrade(img: Image.Image, rng: random.Random) -> Image.Image:
    """Outside-hospital scan: skew, uneven toner, speckle noise, slight blur."""
    angle = rng.uniform(1.2, 2.8) * rng.choice((-1, 1))
    img = img.rotate(angle, resample=Image.BICUBIC, expand=False, fillcolor=255)
    px = img.load()
    for _ in range(int(W * H * 0.004)):  # salt-and-pepper speckles
        px[rng.randrange(W), rng.randrange(H)] = rng.choice((0, 90, 255))
    noise = Image.effect_noise((W, H), 28)
    img = Image.blend(img, noise, 0.12)
    img = img.filter(ImageFilter.GaussianBlur(0.7))
    return img.point(lambda v: min(255, int(v * 0.92 + 18)))  # greyish paper


def render_case(case_dir: Path) -> None:
    case = json.loads((case_dir / "case.json").read_text())
    out = case_dir / "docs"
    out.mkdir(exist_ok=True)
    rng = random.Random(case["case_code"])
    for doc in case["documents"]:
        pages = [
            render_page(lines, doc["facility"], i, len(doc["pages"]))
            for i, lines in enumerate(doc["pages"], start=1)
        ]
        if doc["source"] == "outside":
            pages = [degrade(p, rng) for p in pages]
        pages[0].save(out / doc["filename"], save_all=True, append_images=pages[1:], resolution=150)
        print(f"  {case['case_code']}/{doc['filename']}: {len(pages)} page(s), {doc['source']}")


def check_answer_key(case_dir: Path) -> None:
    """Every answer-key span must be verbatim text from the cited page."""
    case = json.loads((case_dir / "case.json").read_text())
    key = json.loads((case_dir / "answer_key.json").read_text())
    docs = {d["filename"]: d for d in case["documents"]}
    for e in key["events"]:
        page_text = "\n".join(docs[e["document"]]["pages"][e["page"] - 1])
        assert e["span"] in page_text, f"{case['case_code']} {e['id']}: span not on page"


def write_review(case_dirs: list[Path]) -> None:
    out = [
        "# Clinical facts for doctor review",
        "",
        "All cases are **synthetic** (fictional patients and facilities) and exist only to test",
        "OncoReady's extraction and scoring. Please check each fact for clinical plausibility and",
        "internal consistency, tick the box, and note corrections. These facts are the answer key",
        "the pipeline is measured against, so errors here become errors in the recall numbers.",
        "",
        "Generated by `seed/render.py` from `seed/cases/*/answer_key.json`; edit those, not this file.",
        "",
    ]
    for case_dir in case_dirs:
        case = json.loads((case_dir / "case.json").read_text())
        key = json.loads((case_dir / "answer_key.json").read_text())
        out += [f"## {case['case_code']}: {case['title'].removeprefix('Synthetic case: ')}", "", case["summary"], ""]
        out += ["| OK | ID | Date | Category | Fact | Source (doc p.page) |", "|---|---|---|---|---|---|"]
        for e in key["events"]:
            when = e["date"] or "date unclear"
            if e.get("date_precision") in ("month", "year"):
                when = e["date"][:7] if e["date_precision"] == "month" else e["date"][:4]
            out.append(f"| [ ] | {e['id']} | {when} | {e['category']} | {e['fact']} | {e['document']} p.{e['page']} |")
        out.append("")
        derived = (
            [f"Pending test: {p['fact']}" for p in key["pending_tests"]]
            + [f"Discrepancy: {x['fact']}" for x in key["discrepancies"]]
            + [f"Flag: {f['fact']}" for f in key["flags"]]
        )
        if derived:
            out += ["Derived findings (computed in code from the facts above):", ""]
            out += [f"- [ ] {line}" for line in derived]
            out.append("")
        out += ["Rubric items (what a resident's brief should mention):", ""]
        out += [
            f"- [ ] {r['description']} (weight {r['weight']}{', critical' if r['is_critical'] else ''})"
            for r in key["rubric"]
        ]
        out += ["", "Reviewer notes:", "", ""]
    (HERE / "REVIEW_FOR_DOCTOR.md").write_text("\n".join(out))


def main() -> None:
    case_dirs = sorted(p for p in CASES.iterdir() if (p / "case.json").exists())
    for case_dir in case_dirs:
        check_answer_key(case_dir)
        render_case(case_dir)
    write_review(case_dirs)
    print("wrote REVIEW_FOR_DOCTOR.md")


if __name__ == "__main__":
    main()
