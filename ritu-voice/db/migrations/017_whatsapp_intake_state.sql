-- 017 — THE WHATSAPP THREAD REMEMBERS WHERE THE PRE-VISIT INTAKE GOT TO.
--
-- Voice runs a deterministic pre-visit intake after the guards and before the
-- brain (callHandler._maybeHistoryQuestion): "since when?", "any medicines or
-- allergies?", a read-back of the drug it heard. Its state lived in call memory
-- and died with the call. WhatsApp had no intake at all — the twin-parity
-- harness recorded the divergence on 2026-09-04 — and a WhatsApp thread spans
-- days and process restarts, so its state cannot live in memory.
--
-- ONE column, one JSON document per thread (phone_number is UNIQUE):
--   { v: 1,
--     stage: 0 | 1 | 2 | 2.5 | 2.6 | 3,   -- the voice machine's own values
--     readbackPending, readbackDtmfPending, medRepeatPending,   -- objects or null
--     readbackDone, medsHeld, durationReasked, reportAskSent,   -- booleans
--     bookedAt: ms | null,                 -- a booking made in THIS episode
--     at: ms }                             -- last write; a 24h gap starts a new episode
-- NULL = the machine has never run on this thread. The shape is owned by
-- whatsappChannel.hydrateIntake(); nothing else reads the column.
--
-- Additive, transactional (no CONCURRENTLY — see 009 and check-migration-safety).
-- ═══════════════════════════════════════════════════════════════════════════
ALTER TABLE whatsapp_conversations ADD COLUMN IF NOT EXISTS intake JSONB;
